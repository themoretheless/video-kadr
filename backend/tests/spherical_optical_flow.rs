#[test]
fn nonuniform_two_plane_transition_is_queried_at_midpoints_not_source_a() {
    let texture = |x: f64, y: f64| {
        (0.5 + 0.18 * (x * 0.27 + y * 0.19).sin()
            + 0.16 * (x * 0.13 - y * 0.31).cos()
            + 0.10 * (x * 0.53 + y * 0.17).sin()) as f32
    };
    let f = Flow::prepare(
        |lens, u, v| {
            let bx = u * 256. - 0.5;
            let y = v * 128. - 0.5;
            // A has disparity2 on one plane,8 on the other and a slanted depth
            // transition. B is generated by the independent inverse xB=xA+d(xA).
            let ax = if lens == 0 {
                bx
            } else if bx < 98. {
                bx - 2.
            } else if bx <= 128. {
                (bx + 22.) / 1.25
            } else {
                bx - 8.
            };
            let z = texture(ax, y);
            Some([z, z, z, 1.])
        },
        Stitching {
            search_radius: 8,
            ..config()
        },
        &mut || Ok(()),
    )
    .unwrap();
    let expected = 2. + 0.25 * ((120. + 11.) / 1.125 - 96.);
    let (mut error, mut trusted) = (0., 0);
    for y in [40.5, 60.5, 80.5] {
        let (d, c) = f.displacement(120.5 / 256., y / 128.).unwrap();
        let e = (d[0] * 256. - expected).abs();
        println!(
            "nonuniform midpoint dx={} expected={expected} confidence={c}",
            d[0] * 256.
        );
        if c >= 0.3 {
            error += e;
            trusted += 1;
        } else if e > 0.25 {
            assert!(
                c < 0.15,
                "ambiguous texture must not create a trusted wrong-depth warp"
            );
        }
    }
    assert!(trusted>=2&&error/(trusted as f64)<0.2,"A-grid lookup would incorrectly return the far-plane8px displacement at reliable points");
    for (x, expected) in [(72.5, 2.), (144.5, 8.)] {
        let (d, _) = f.displacement(x / 256., 60.5 / 128.).unwrap();
        assert!((d[0] * 256. - expected).abs() < 0.2);
    }
}
