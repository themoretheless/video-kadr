fn image_value(lon: f64, lat: f64) -> u8 {
    // Smooth, unique multiscale texture survives fisheye resampling at the seam.
    let v = 0.5
        + 0.19 * (lon * 37. + lat * 7.).sin()
        + 0.13 * (lon * 19. - lat * 29.).cos()
        + 0.1 * (lon * 71. + lat * 43.).sin();
    (v.clamp(0., 1.) * 255.).round() as u8
}
fn synthetic_fisheyes(sample: impl Fn(usize, f64, f64) -> u8) -> GroupSurface {
    let mut image = GroupSurface::transparent(512, 256).unwrap();
    let half = 110f64.to_radians();
    for y in 0..256 {
        for x in 0..512 {
            let lens = usize::from(x >= 256);
            let nx = (x as f64 + 0.5 - (if lens == 0 { 128. } else { 384. })) / 128.;
            let ny = (128. - (y as f64 + 0.5)) / 128.;
            let r = nx.hypot(ny);
            let at = (y * 512 + x) * 4;
            if r > 1. {
                continue;
            }
            let theta = r * half;
            let az = ny.atan2(nx);
            let (mut dx, dy, mut dz) =
                (theta.sin() * az.cos(), theta.sin() * az.sin(), theta.cos());
            if lens == 1 {
                dx = -dx;
                dz = -dz
            }
            let lon = dx.atan2(dz);
            let lat = dy.asin();
            let value = sample(lens, lon, lat);
            image.rgba[at..at + 4].copy_from_slice(&[value, value, value, 255]);
        }
    }
    image
}
fn shifted_fisheyes(shift: f64) -> GroupSurface {
    synthetic_fisheyes(|lens, lon, lat| image_value(lon - if lens == 1 { shift } else { 0. }, lat))
}
