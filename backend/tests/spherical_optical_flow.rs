fn texture(x: usize, y: usize) -> f32 {
    let mut h = (x as u32).wrapping_mul(374761393) ^ (y as u32).wrapping_mul(668265263);
    h = (h ^ (h >> 13)).wrapping_mul(1274126177);
    ((h ^ (h >> 16)) & 255) as f32 / 255.
}
fn config() -> Stitching {
    Stitching {
        mode: Mode::OpticalFlow,
        search_radius: 5,
        strength: 1.,
        occlusion_strength: 0.,
    }
}
fn ownership_config() -> Stitching {
    Stitching {
        occlusion_strength: 1.,
        ..config()
    }
}
