fn native_occluded_flat_near_object_uses_one_view_without_erasing_foreground() {
    // Textureless foreground disparity exceeds the search range. No patch flow
    // can infer its missing correspondences; the visible owner must retain it.
    let source = synthetic_fisheyes(|lens, lon, lat| {
        let centre = std::f64::consts::FRAC_PI_2 + if lens == 0 { -0.11 } else { 0.11 };
        if (lon - centre).abs() < 0.24 && lat.abs() < 0.30 {
            230
        } else {
            40
        }
    });
    let feather = render(source.clone(), false);
    let optical = render_stitching(
        source,
        Some(Stitching {
            search_radius: 8,
            ..ownership_config()
        }),
    );
    for (a, b) in optical
        .rgba
        .chunks_exact(4)
        .zip(feather.rgba.chunks_exact(4))
    {
        assert!(
            a[3] as i32 >= b[3] as i32 - 1,
            "ownership must preserve baseline coverage"
        );
    }
    let count = |image: &GroupSurface| {
        let mut ghost = 0;
        let mut foreground = 0;
        for y in 109..147 {
            for x in 346..422 {
                let v = image.rgba[(y * 512 + x) * 4];
                ghost += usize::from(v > 65 && v < 210);
                foreground += usize::from(v >= 210);
            }
        }
        (ghost, foreground)
    };
    let (before, old_foreground) = count(&feather);
    let (after, foreground) = count(&optical);
    println!("flat near-object intermediate pixels {before}->{after}; solid foreground {old_foreground}->{foreground}");
    assert!(before > 100);
    assert!(
        after < before / 3,
        "residual occlusion must not make two translucent edges"
    );
    assert!(
        foreground >= old_foreground,
        "ownership must preserve the foreground rather than hide the ghost by erasing the object"
    );
    assert!(
        foreground < 38 * 65,
        "ownership must not fill the entire background region"
    );
}
#[test]
fn semantic_seed_projection_uses_the_same_visible_near_object_owner() {
    let source = synthetic_fisheyes(|lens, lon, lat| {
        let centre = std::f64::consts::FRAC_PI_2 + if lens == 0 { -0.11 } else { 0.11 };
        if (lon - centre).abs() < 0.24 && lat.abs() < 0.30 {
            230
        } else {
            40
        }
    });
    let mut parameters = SphericalVideo {
        input: Input::DualFisheye,
        output: Output::Equirectangular,
        stabilization_mode:
            video_kadr_backend::domain::spherical_video::StabilizationMode::Disabled,
        ..Default::default()
    };
    parameters.lenses[0].fov = 220.;
    parameters.lenses[1].fov = 220.;
    let mask: Vec<u8> = (0..128)
        .flat_map(|_| (0..256).map(|x| if x < 128 { 255 } else { 0 }))
        .collect();
    let before = parameters
        .project_tracking_mask(&mask, 256, 128, 0., &source, &mut || Ok(()))
        .unwrap();
    parameters.stitching = Stitching {
        search_radius: 8,
        ..ownership_config()
    };
    let after = parameters
        .project_tracking_mask(&mask, 256, 128, 0., &source, &mut || Ok(()))
        .unwrap();
    // A global cut can select either complete source view. The seed must
    // follow that actual visible color, rather than a fixed-axis assumption.
    let at = 128 * 256 + 200;
    let color = render_stitching(
        source.clone(),
        Some(Stitching {
            search_radius: 8,
            ..ownership_config()
        }),
    )
    .rgba[(128 * 512 + 401) * 4];
    assert!(before[at] > 250);
    assert!(
        color < 60 || color > 215,
        "away from the cut the object must stay opaque"
    );
    if color > 215 {
        assert!(
            after[at] < 5,
            "lens1 foreground must exclude the incompatible lens0 seed"
        );
    } else {
        assert!(after[at] > 250, "visible lens0 must retain its source seed");
    }
    // Where both views agree retain the conservative source-mask union.
    assert_eq!(after[128 * 256 + 193], before[128 * 256 + 193]);
}
#[test]
fn global_cut_routes_around_observable_foreground_and_preserves_one_whole_object() {
    let sample = |lens: usize, u: f64, v: f64| {
        if (lens == 0 && u > 0.75) || (lens == 1 && u < 0.25) {
            return None;
        }
        let centre = if lens == 0 { 0.44 } else { 0.56 };
        let local = u - centre;
        let foreground = local.abs() < 0.14 && (0.30..0.70).contains(&v);
        let rgb = if foreground {
            [
                0.55 + 0.25 * (local + 0.14) / 0.28,
                0.50 + 0.12 * (local * 110.).sin(),
                0.2,
            ]
        } else {
            [0.1; 3]
        };
        let priority = if lens == 0 { 0.75 - u } else { u - 0.25 };
        Some(([rgb[0] as f32, rgb[1] as f32, rgb[2] as f32, 1.], priority))
    };
    // Freeze the geometry to isolate ownership. The two observable textured
    // projections overlap but have different silhouettes: a fixed-axis cut
    // splices them into an over-wide foreground. A global cut can go around it.
    let flow = Flow::prepare_with_priority(
        sample,
        Stitching {
            strength: 0.,
            search_radius: 2,
            ..ownership_config()
        },
        &mut || Ok(()),
    )
    .unwrap();
    let mut pixels = Vec::new();
    let mut owners = Vec::new();
    for x in 0..256 {
        let u = (x as f64 + 0.5) / 256.;
        let owner = flow
            .ownership(u, 0.5)
            .expect("graph budget must cover ordinary overlap");
        let a = sample(0, u, 0.5);
        let b = sample(1, u, 0.5);
        let color = match (a, b) {
            (Some((a, _)), Some((b, _))) => a[0] as f64 * owner + b[0] as f64 * (1. - owner),
            (Some((a, _)), None) => a[0] as f64,
            (None, Some((b, _))) => b[0] as f64,
            _ => 0.,
        };
        pixels.push(color > 0.3);
        if (0.31..0.69).contains(&u) {
            owners.push(owner);
        }
    }
    let foreground = pixels.iter().filter(|v| **v).count();
    let components = pixels
        .iter()
        .enumerate()
        .filter(|(i, v)| **v && (*i == 0 || !pixels[*i - 1]))
        .count();
    println!("global seam foreground pixels={foreground}, connectedComponents={components}");
    assert!(
        (68..=76).contains(&foreground),
        "retain one source object's width, not their union or an erased foreground"
    );
    assert_eq!(components, 1);
    assert!(
        owners.iter().all(|v| *v < 0.01) || owners.iter().all(|v| *v > 0.99),
        "cut must route around the observable object"
    );
    assert!(
        Flow::prepare_with_priority(sample, config(), &mut || anyhow::bail!("cancel")).is_err()
    );
}
#[test]
fn seam_ownership_retains_agreeing_color_coverage_and_zero_strength() {
    use video_kadr_backend::domain::spherical_optical_flow::seam_weights;
    let a = [0.2, 0.3, 0.4, 1.];
    let b = [0.21, 0.29, 0.39, 1.];
    assert_eq!(
        seam_weights([a, b], [0.4, 0.6], 1., 0., Some(0.)),
        [0.4, 0.6]
    );
    assert_eq!(
        seam_weights([a, [0.9, 0.9, 0.9, 1.]], [0.4, 0.6], 0., 0., Some(1.)),
        [0.4, 0.6]
    );
    assert_eq!(
        seam_weights([a, [0.; 4]], [0.4, 0.], 1., 0., Some(1.)),
        [0.4, 0.]
    );
    assert_eq!(
        seam_weights([a, [0.9, 0.9, 0.9, 1.]], [0.6, 0.4], 1., 1., Some(1.)),
        [0.6, 0.4],
        "supported alignment must preserve midpoint blending"
    );
    assert_eq!(
        seam_weights([a, [0.9, 0.9, 0.9, 1.]], [0.6, 0.4], 1., 0., None),
        [0.6, 0.4],
        "missing/budget-limited cut must keep original blending"
    );
    let w = seam_weights([a, [0.9, 0.9, 0.9, 1.]], [0.6, 0.4], 1., 0., Some(1.));
    assert_eq!(w, [1., 0.]);
    let w = seam_weights([a, [0.9, 0.9, 0.9, 1.]], [0.5, 0.5], 1., 0., Some(0.5));
    assert!((w[0] - 0.5).abs() < 1e-12 && w.iter().sum::<f64>() == 1.);
}
fn render(src: GroupSurface, optical: bool) -> GroupSurface {
    render_stitching(
        src,
        if optical {
            Some(Stitching {
                search_radius: 8,
                ..config()
            })
        } else {
            None
        },
    )
}
fn render_stitching(mut src: GroupSurface, stitching: Option<Stitching>) -> GroupSurface {
    let mut p = SphericalVideo {
        input: Input::DualFisheye,
        output: Output::Equirectangular,
        ..Default::default()
    };
    p.lenses[0].fov = 220.;
    p.lenses[1].fov = 220.;
    if let Some(stitching) = stitching {
        p.stitching = stitching;
    }
    flat_surface::apply_effect_stack(
        &mut src,
        &[VideoEffect::SphericalVideo {
            parameters: p,
            animation: None,
        }],
        0,
        &[],
        &mut || Ok(()),
    )
    .unwrap();
    src
}
#[test]
fn native_stitch_renderer_reduces_textured_overlap_ghosting_and_preserves_alpha() {
    let shift = 3. * std::f64::consts::TAU / 256.;
    let source = shifted_fisheyes(shift);
    let feather = render(source.clone(), false);
    let optical = render(source, true);
    let mut before = 0.;
    let mut after = 0.;
    let mut count = 0;
    for y in 48..208 {
        for x in [128usize, 384usize] {
            for dx in -4..=4 {
                let x = (x as i32 + dx) as usize;
                let lon = ((x as f64 + 0.5) / 512. - 0.5) * std::f64::consts::TAU;
                let lat = (0.5 - (y as f64 + 0.5) / 256.) * std::f64::consts::PI;
                let expected = image_value(lon - shift * 0.5, lat) as f64;
                let at = (y * 512 + x) * 4;
                before += (feather.rgba[at] as f64 - expected).powi(2);
                after += (optical.rgba[at] as f64 - expected).powi(2);
                assert_eq!(optical.rgba[at + 3], 255);
                count += 1;
            }
        }
    }
    println!(
        "overlap midpoint MSE feather={} optical={} ratio={}",
        before / count as f64,
        after / count as f64,
        after / before
    );
    assert!(
        after < before * 0.25,
        "ownership must preserve the previously qualified textured midpoint registration"
    );
    assert!(SphericalVideo {
        stitching: config(),
        ..Default::default()
    }
    .validate()
    .is_err());
}

#[test]
fn subpixel_matches_have_small_mean_bias_on_band_limited_texture() {
    let mut base = vec![0f32; 256 * 128];
    for y in 0..128 {
        for x in 0..256 {
            let mut value = 0.;
            for dy in -1i32..=1 {
                for dx in -1i32..=1 {
                    let weight = (if dx == 0 { 2. } else { 1. }) * (if dy == 0 { 2. } else { 1. });
                    value += texture(
                        (x as i32 + dx).rem_euclid(256) as usize,
                        (y as i32 + dy).rem_euclid(128) as usize,
                    ) * weight
                        / 16.;
                }
            }
            base[y * 256 + x] = value;
        }
    }
    for shift in [0.2, 0.4, 0.7] {
        let flow = Flow::prepare(
            |lens, u, v| {
                let x = (u * 256. - 0.5 - if lens == 1 { shift } else { 0. }).rem_euclid(256.);
                let y = (v * 128. - 0.5).clamp(0., 127.);
                let ix = x.floor() as usize;
                let iy = y.floor() as usize;
                let tx = (x - x.floor()) as f32;
                let ty = (y - y.floor()) as f32;
                let at = |x: usize, y: usize| base[y.min(127) * 256 + x % 256];
                let value = (at(ix, iy) * (1. - tx) + at(ix + 1, iy) * tx) * (1. - ty)
                    + (at(ix, iy + 1) * (1. - tx) + at(ix + 1, iy + 1) * tx) * ty;
                Some([value, value, value, 1.])
            },
            Stitching {
                search_radius: 2,
                ..config()
            },
            &mut || Ok(()),
        )
        .unwrap();
        let values: Vec<_> = flow
            .correspondences()
            .iter()
            .filter(|p| {
                p.from[0] > 0.15
                    && p.from[0] < 0.85
                    && p.from[1] > 0.2
                    && p.from[1] < 0.8
                    && p.confidence > 0.7
            })
            .map(|p| (p.to[0] - p.from[0]) * 256.)
            .collect();
        assert!(values.len() > 100);
        let mean = values.iter().sum::<f64>() / values.len() as f64;
        println!(
            "subpixel shift {shift}: measured mean {mean}, nodes {}",
            values.len()
        );
        assert!((mean - shift).abs() < 0.05);
    }
}

