import { expect, test } from '@playwright/test'
if (process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE) test.use({ launchOptions: { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE } })
test('production DSP controls use real native catalog and retain cursor keys', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const response = page.waitForResponse(r => new URL(r.url()).pathname === '/api/compositions/audio-dsp-catalog' && r.status() === 200)
  await page.goto('/e2e/fixtures/live-dsp.html')
  const catalog = await (await response).json()
  const amplify = catalog.effects.find((effect: { id: string }) => effect.id === 'amplify')
  expect(amplify.nativeExport).toBe(true)
  await page.getByLabel('Добавить DSP эффект').selectOption('amplify')
  const gain = page.getByLabel('DSP 1 Gain', { exact: true })
  expect(await gain.getAttribute('min')).toBe(String(amplify.params[0].min))
  await gain.fill('-6'); await gain.dispatchEvent('change')
  await page.getByLabel('Ключ DSP 1 Gain', { exact: true }).click()
  const authored = async () => JSON.parse(await page.getByLabel('Authored DSP chain').innerText())
  expect((await authored())[0].animation.gain.track.keyframes).toEqual([{ tick: 500000, value: -6 }])
  await page.getByLabel('DSP cursor').fill('1000000')
  await gain.fill('3'); await gain.dispatchEvent('change')
  expect((await authored())[0].animation.gain.track.keyframes).toEqual([{ tick: 500000, value: -6 }, { tick: 1000000, value: 3 }])
  await page.getByLabel('Интерполяция DSP 1 Gain', { exact: true }).selectOption('hold')
  expect((await authored())[0].animation.gain.track.interpolation).toBe('hold')
  await page.getByText('Ключи (2)', { exact: true }).click()
  const time = page.getByLabel('DSP 1 Gain ключ 1 время', { exact: true })
  await time.fill('0.25'); await time.dispatchEvent('change')
  const value = page.getByLabel('DSP 1 Gain ключ 1 значение', { exact: true })
  await value.fill('-3'); await value.dispatchEvent('change')
  expect((await authored())[0].animation.gain.track.keyframes).toEqual([{ tick: 250000, value: -3 }, { tick: 1000000, value: 3 }])
  await page.getByLabel('Удалить ключ DSP 1 Gain 1', { exact: true }).click()
  expect((await authored())[0].animation.gain.track.keyframes).toEqual([{ tick: 1000000, value: 3 }])
  await page.getByLabel('Bypass DSP 1').check()
  expect((await authored())[0].bypass).toBe(true)
  await page.getByLabel('Bypass DSP 1').uncheck()
  await expect(page.getByText('DSP применяется в нативном экспорте;', { exact: false })).toBeVisible()
  if (process.env.DSP_SCREENSHOT_PATH) await page.screenshot({ path: process.env.DSP_SCREENSHOT_PATH, fullPage: true })
  await page.getByLabel('Убрать кривую DSP 1 Gain', { exact: true }).click()
  expect((await authored())[0].animation).toEqual({})
  await page.getByLabel('Удалить DSP 1', { exact: true }).click()
  expect(await authored()).toEqual([])
  await page.getByLabel('Добавить DSP эффект', { exact: true }).selectOption('filmcraft:delay')
  const sourceDelay = page.getByLabel('DSP 1 Delay (s)', { exact: true })
  await expect(sourceDelay).toHaveValue('1')
  await sourceDelay.fill('0.4'); await sourceDelay.dispatchEvent('change')
  await page.getByLabel('Ключ DSP 1 Delay (s)', { exact: true }).click()
  expect((await authored())[0].id).toBe('filmcraft:delay')
  expect((await authored())[0].params.delay).toBe(0.4)
  expect((await authored())[0].animation.delay.track.keyframes).toEqual([{ tick: 1000000, value: 0.4 }])
  if (process.env.DSP_SCREENSHOT_PATH) await page.screenshot({ path: process.env.DSP_SCREENSHOT_PATH, fullPage: true })
  await page.getByLabel('Удалить DSP 1', { exact: true }).click()
  let characteristicResponses = 0
  page.on('response', response => { if (new URL(response.url()).pathname === '/api/compositions/audio-project-response' && response.status() === 200) characteristicResponses++ })
  await page.getByLabel('Добавить DSP эффект', { exact: true }).selectOption('filmcraft:highpass')
  await page.getByText('Характеристики эффекта', { exact: true }).click()
  const frequencyGraph = page.getByRole('img', { name: 'Частотная характеристика', exact: true })
  await expect(frequencyGraph).toBeVisible()
  const initialPath = await frequencyGraph.locator('.curve').getAttribute('d')
  expect(initialPath).toMatch(/^M/)
  const cutoff = page.getByLabel('DSP 1 Cutoff (Hz)', { exact: true })
  await cutoff.fill('1000'); await cutoff.dispatchEvent('change')
  await expect.poll(() => frequencyGraph.locator('.curve').getAttribute('d')).not.toBe(initialPath)
  const firstKeyPath = await frequencyGraph.locator('.curve').getAttribute('d')
  await page.getByLabel('Ключ DSP 1 Cutoff (Hz)', { exact: true }).click()
  await page.getByLabel('DSP cursor').fill('2000000')
  await cutoff.fill('2000'); await cutoff.dispatchEvent('change')
  await expect(frequencyGraph).toBeVisible()
  await expect.poll(() => frequencyGraph.locator('.curve').getAttribute('d')).not.toBe(firstKeyPath)
  const secondKeyPath = await frequencyGraph.locator('.curve').getAttribute('d')
  await page.getByLabel('DSP cursor').fill('1000000')
  await expect.poll(() => frequencyGraph.locator('.curve').getAttribute('d')).not.toBe(secondKeyPath)
  expect((await authored())[0].params.cutoff).toBe(2000)
  await page.getByLabel('Автоматизация на курсоре', { exact: true }).uncheck()
  await expect.poll(() => frequencyGraph.locator('.curve').getAttribute('d')).toBe(secondKeyPath)
  await page.getByLabel('Автоматизация на курсоре', { exact: true }).check()
  await page.getByLabel('Частота дискретизации характеристики', { exact: true }).selectOption('44100')
  await expect(frequencyGraph).toBeVisible()
  if (process.env.DSP_SCREENSHOT_PATH) await page.screenshot({ path: process.env.DSP_SCREENSHOT_PATH, fullPage: true })
  const responsesBeforeMoves = characteristicResponses
  const keptVisible = await page.evaluate(async () => {
    const cursor = document.querySelector<HTMLInputElement>('[aria-label="DSP cursor"]')!
    let visible = true
    const shapes = new Set<string>()
    for (let i = 0; i < 40; i++) {
      cursor.value = String(1000000 + i * 20000)
      cursor.dispatchEvent(new Event('input', { bubbles: true }))
      await new Promise(resolve => setTimeout(resolve, 20))
      const graph = document.querySelector('[aria-label="Частотная характеристика"]')
      visible &&= graph !== null
      const shape = graph?.querySelector('.curve')?.getAttribute('d')
      if (shape) shapes.add(shape)
    }
    return { visible, shapes: shapes.size }
  })
  expect(keptVisible.visible).toBe(true)
  expect(keptVisible.shapes).toBeGreaterThanOrEqual(2)
  expect(characteristicResponses - responsesBeforeMoves).toBeGreaterThanOrEqual(2)
  await page.getByLabel('Удалить DSP 1', { exact: true }).click()
  await page.getByLabel('Добавить DSP эффект', { exact: true }).selectOption('filmcraft:dynamics')
  await page.getByText('Характеристики эффекта', { exact: true }).click()
  await expect(page.getByRole('img', { name: 'Характеристика компрессии', exact: true })).toBeVisible()
  expect(errors).toEqual([])
})
