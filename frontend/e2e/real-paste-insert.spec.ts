import {expect,test} from '@playwright/test'
test('Paste Insert and sync-lock work through actual timeline controls with Undo/Redo',async({page})=>{
 test.setTimeout(120_000)
 const fixture=process.env.REAL_COMPOSITION_FIXTURE
 if(!fixture)throw new Error('REAL_COMPOSITION_FIXTURE is required')
 const errors:string[]=[]
 page.on('pageerror',error=>errors.push(error.message))
 await page.goto('/')
 await page.getByRole('button',{name:'Multitrack',exact:true}).click()
 await expect(page.getByLabel('Название композиции')).toHaveValue('Новая композиция',{timeout:60_000})
 await page.locator('.dropzone input[type="file"]').setInputFiles(fixture)
 const clips=page.locator('.composition-clip.video')
 await expect(clips).toHaveCount(1)
 await clips.first().click()
 await page.keyboard.press('Control+c')
 const paste=page.getByRole('button',{name:'Вставить со сдвигом',exact:true})
 await expect(paste).toBeEnabled()
 const sync=page.locator('button[title="Sync-lock при вставке"]').first()
 await expect(sync).toHaveAttribute('aria-pressed','true')
 await sync.click()
 await expect(sync).toHaveAttribute('aria-pressed','false')
 const slider=page.getByLabel('Плейхед',{exact:true})
 await slider.evaluate((element:HTMLInputElement)=>{element.value='500000';element.dispatchEvent(new Event('input',{bubbles:true}))})
 await paste.click()
 await expect(clips).toHaveCount(3)
 await expect(slider).toHaveValue('1500000')
 await page.getByRole('button',{name:'Отменить',exact:true}).click()
 await expect(clips).toHaveCount(1)
 await expect(sync).toHaveAttribute('aria-pressed','false')
 await page.getByRole('button',{name:'Повторить',exact:true}).click()
 await expect(clips).toHaveCount(3)
 await expect(page.locator('body')).not.toContainText('setProjectReviewMember,')
 expect(errors).toEqual([])
 await page.screenshot({path:'/tmp/video-kadr-stage1602-paste-insert-browser.png',fullPage:true})
})
