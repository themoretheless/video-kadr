import {readFile} from 'node:fs/promises'
import {expect,test} from '@playwright/test'
if(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE)test.use({launchOptions:{executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE}})
test('real authorized scopes decode uploaded video and render a four-scope preset',async({page,request})=>{
 const path=process.env.REAL_COMPOSITION_FIXTURE;if(!path)throw new Error('REAL_COMPOSITION_FIXTURE required')
 const registered=await request.post('/api/auth/register',{data:{username:'scope-browser-user',password:'scope-browser-test-password'}});expect(registered.status()).toBe(201)
 const {token}=await registered.json() as {token:string}
 const uploaded=await request.post('/api/upload',{headers:{Authorization:`Bearer ${token}`},multipart:{file:{name:'scope-fixture.mp4',mimeType:'video/mp4',buffer:await readFile(path)}}});expect(uploaded.ok()).toBe(true)
 const {id}=await uploaded.json() as {id:string};expect(id).toBeTruthy()
 const constant=(value:number)=>({mode:'constant',value})
 const content={schemaVersion:1,timeBase:1000000,canvas:{width:160,height:90,fpsMilli:10000,background:{red:0,green:0,blue:0,alpha:1}},sources:{[id]:{id,kind:'video',durationTicks:1000000,width:160,height:90,hasAudio:true}},tracks:[{kind:'video',id:'main',name:'Video',hidden:false,locked:false,clips:[{id:'clip',sourceId:id,placement:{timelineStartTick:0,sourceInTick:0,sourceOutTick:1000000,speed:1},transform:{x:constant(0),y:constant(0),scaleX:constant(1),scaleY:constant(1),rotationDegrees:constant(0),anchorX:0.5,anchorY:0.5},opacity:constant(1),blendMode:'normal',effects:[],enabled:true}],transitions:[]}]}
 const props={project:{schemaVersion:1,root:'root',compositions:{root:{durationUs:1000000,content,instances:[]}}},timeUs:500000,token,renderedOutputs:{},compositionId:'root'}
 await page.addInitScript(value=>localStorage.setItem('video-kadr.live-scope-test',JSON.stringify(value)),props)
 let previews=0;page.on('request',r=>{if(new URL(r.url()).pathname==='/api/compositions/nested-preview')previews++})
 await page.goto('/e2e/fixtures/live-scopes.html')
 const response=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/compositions/scopes-rgba'&&r.status()===200)
 await page.getByText('Lumetri Scopes',{exact:true}).click()
 const levels=await (await response).json();expect(levels.samples).toEqual([160,90]);expect(levels.stats.b.mean).toBeGreaterThan(levels.stats.r.mean)
 await expect(page.getByRole('table',{name:'Scopes уровни'})).toBeVisible()
 const before=previews
 const four=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/compositions/scopes-rgba'&&r.status()===200)
 await page.getByLabel('Scopes пресет').selectOption('Four Scopes (RGB, 8 bit)')
 const nativeFour=await (await four).json();await expect(page.locator('canvas')).toHaveCount(4)
 await expect(page.locator('svg.foreground line')).toHaveCount(2)
 expect(previews).toBe(before)
 for(const canvas of await page.locator('canvas').all())expect(await canvas.evaluate(el=>{const c=el as HTMLCanvasElement;return c.width>0&&Array.from(c.getContext('2d')!.getImageData(0,0,c.width,c.height).data).some(v=>v>0)})).toBe(true)
 const hdrResponse=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/compositions/scopes-rgba'&&r.status()===200)
 await page.getByLabel('Scopes шкала').selectOption('hdr')
 const nativeHdr=await (await hdrResponse).json()
 expect(nativeHdr.vectorscopeYuv).toEqual(nativeFour.vectorscopeYuv)
 expect(nativeHdr.stats).toEqual(nativeFour.stats)
 await expect(page.locator('.axis-unit')).toHaveCount(3)
 expect(previews).toBe(before)
 const explicitResponse=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/compositions/scopes-rgba'&&r.status()===200)
 await page.getByLabel('Scopes матрица').selectOption('Bt601')
 expect((await (await explicitResponse).json()).matrix).toBe('Bt601')
 const autoResponse=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/compositions/scopes-rgba'&&r.status()===200)
 await page.getByLabel('Scopes матрица').selectOption('auto')
 const automatic=await (await autoResponse).json();expect(automatic.matrix).toBe('Bt709');expect(automatic.stats).toEqual(nativeHdr.stats);expect(automatic.vectorscopeYuv).toEqual(nativeHdr.vectorscopeYuv)
 expect(previews).toBe(before)
 let release!:()=>void
 await page.route('**/api/compositions/nested-preview',async route=>{await new Promise<void>(resolve=>{release=resolve});await route.continue()})
 const nextPreview=page.waitForRequest(r=>new URL(r.url()).pathname==='/api/compositions/nested-preview')
 await page.getByRole('button',{name:'Next scope frame'}).click();await nextPreview
 await expect(page.locator('.graphs')).toHaveAttribute('aria-busy','true')
 await expect(page.getByRole('table',{name:'Scopes уровни'})).toBeVisible()
 for(const canvas of await page.locator('canvas').all())expect(await canvas.evaluate(el=>{const c=el as HTMLCanvasElement;return Array.from(c.getContext('2d')!.getImageData(0,0,c.width,c.height).data).some(v=>v>0)})).toBe(true)
 const nextAnalysis=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/compositions/scopes-rgba'&&r.status()===200)
 release();await nextAnalysis;await expect(page.locator('.graphs')).toHaveAttribute('aria-busy','false')
 expect(previews).toBe(before+1)
 await page.unroute('**/api/compositions/nested-preview')
 await page.locator('.graphs').click({button:'right'})
 const settings=page.getByRole('dialog',{name:'Настройки Scopes'});await expect(settings).toBeVisible()
 const menuAnalysis=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/compositions/scopes-rgba'&&r.status()===200)
 await settings.getByLabel('Scopes пресет').selectOption('Waveform (Luma)');await menuAnalysis
 await expect(page.locator('canvas')).toHaveCount(1)
 await page.keyboard.press('Escape');await expect(settings).toHaveCount(0)
 await expect(page.locator('.graphs')).toBeFocused()
 await expect(page.locator('.scope-name')).toHaveText('Waveform (Luma)')
 await expect(page.getByLabel('Цветовое пространство Scopes',{exact:true})).toHaveText('Rec. 709')
 await page.screenshot({path:process.env.SCOPE_SCREENSHOT_PATH??'test-results/live-scopes.png'})
})
